// Scores the cover solver and the "first free member" baseline against the oracle's labels.
//   npx tsx eval/run.ts            development set (60)
//   npx tsx eval/run.ts --heldout  held-out set (20), run once the solver is frozen
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import type { Visit } from "../shared/domain.ts";
import { households, members, seedVisits } from "../shared/seed.ts";
import { firstFree, solve, type Assignment } from "../server/dispatch/solver.ts";
import { violations, type Labels, type Scenario } from "./oracle.ts";

const heldout = process.argv.includes("--heldout");
const dir = heldout ? "eval/heldout" : "eval/disruptions";
const week = seedVisits();
const meta = JSON.parse(readFileSync(`${dir}/meta.json`, "utf8")) as { worldHash: string };
const hash = createHash("sha256").update(JSON.stringify({ members, households, week })).digest("hex").slice(0, 16);
if (hash !== meta.worldHash) throw new Error(`seed week changed since the labels were made (${hash} != ${meta.worldHash})`);
const stored = JSON.parse(readFileSync(`${dir}/scenarios.json`, "utf8")) as Scenario[];
const labels = new Map((JSON.parse(readFileSync(`${dir}/labels.json`, "utf8")) as Labels[]).map((l) => [l.scenarioId, l]));
const world = { members, households };

export function rebuild(s: Scenario): Scenario {
  const over = new Map(s.visits.map((v) => [v.id, v]));
  const visits: Visit[] = week.map((v) => over.get(v.id) ?? v);
  for (const v of s.visits) if (!week.some((w) => w.id === v.id)) visits.push(v);
  return { ...s, visits };
}

function apply(s: Scenario, as: Assignment[]): Visit[] {
  const by = new Map(as.map((a) => [a.visitId, a.memberId]));
  return s.visits.map((v) => (by.has(v.id) ? { ...v, memberIds: by.get(v.id) ? [by.get(v.id)!] : [] } : v));
}

function consentBroken(as: Assignment[], s: Scenario): number {
  return as.filter((a) => {
    if (!a.memberId) return false;
    const v = s.visits.find((x) => x.id === a.visitId)!;
    const h = households.find((x) => x.id === v.householdId)!;
    return h.sameCleaner && h.regularMemberId !== a.memberId;
  }).length;
}

const rows: string[] = [];
const tot = {
  affected: 0,
  oracle: 0,
  solver: 0,
  solverAtMax: 0,
  solverViol: 0,
  solverConsentAsked: 0,
  minConsent: 0,
  base: 0,
  baseViolVisits: 0,
  baseConsentUnasked: 0,
  healthyProposals: 0,
  ms: 0,
  explored: 0,
};
for (const raw of stored) {
  const s = rebuild(raw);
  const l = labels.get(s.id)!;
  const input = { members, households, visits: s.visits, absences: s.absent, affected: s.affected };
  const t0 = performance.now();
  const r = solve(input);
  const ms = performance.now() - t0;
  const best = r.plans[0];
  const plan = best?.assignments ?? s.affected.map((id) => ({ visitId: id, memberId: null, consent: false, language: false, familiar: false, travelIn: 0 }));
  const sv = violations(world, apply(s, plan), s.absent);
  const base = firstFree(input);
  const bv = violations(world, apply(s, base), s.absent);
  const baseBadVisits =
    new Set(
      bv
        .map((x) => x.split(":")[0]!.split("+"))
        .flat()
        .filter((id) => s.affected.includes(id)),
    ).size + consentBroken(base, s);
  const covered = plan.filter((a) => a.memberId).length;
  tot.affected += s.affected.length;
  tot.oracle += l.maxCovered;
  tot.solver += covered;
  tot.solverAtMax += covered === l.maxCovered ? 1 : 0;
  tot.solverViol += sv.length;
  tot.solverConsentAsked += best?.consent ?? 0;
  tot.minConsent += l.minConsent;
  tot.base += base.filter((a) => a.memberId).length;
  tot.baseViolVisits += baseBadVisits;
  tot.baseConsentUnasked += consentBroken(base, s);
  if (s.kind === "healthy") tot.healthyProposals += plan.length;
  tot.ms += ms;
  tot.explored += r.explored;
  rows.push(
    `| ${s.id} | ${s.kind} | ${s.affected.length} | ${l.maxCovered} | ${covered} | ${sv.length} | ${best?.consent ?? 0}/${l.minConsent} | ${base.filter((a) => a.memberId).length} | ${baseBadVisits} | ${ms.toFixed(1)} |`,
  );
}

const n = stored.length;
const summary = {
  set: heldout ? "held-out" : "development",
  scenarios: n,
  affectedVisits: tot.affected,
  oracleMaxCovered: tot.oracle,
  solverCovered: tot.solver,
  solverScenariosAtOracleMax: tot.solverAtMax,
  solverConstraintViolations: tot.solverViol,
  solverConsentRequests: tot.solverConsentAsked,
  oracleMinConsent: tot.minConsent,
  healthyScenarioProposals: tot.healthyProposals,
  baselinePlaced: tot.base,
  baselineVisitsBreakingARule: tot.baseViolVisits,
  baselineSameCleanerWithoutAsking: tot.baseConsentUnasked,
  solverMsTotal: Math.round(tot.ms),
  solverMsMean: +(tot.ms / n).toFixed(1),
};
const md = [
  `# Cover evaluation, ${summary.set} set`,
  "",
  `Generated by \`npx tsx eval/run.ts${heldout ? " --heldout" : ""}\`. Labels come from \`eval/oracle.ts\`, which enumerates every assignment with its own constraint checks.`,
  "",
  "| | Solver | First free member |",
  "|---|---|---|",
  `| Visits placed (oracle maximum ${tot.oracle} of ${tot.affected}) | ${tot.solver} | ${tot.base} |`,
  `| Scenarios at the oracle maximum | ${tot.solverAtMax} / ${n} | |`,
  `| Placed visits breaking a rule (availability, skills, travel, hours, same cleaner) | ${tot.solverViol} | ${tot.baseViolVisits} |`,
  `| Same-cleaner households asked first | ${tot.solverConsentAsked} (oracle minimum ${tot.minConsent}) | 0 asked, ${tot.baseConsentUnasked} reassigned without asking |`,
  `| Proposals on ordinary days | ${tot.healthyProposals} | |`,
  `| Solve time | ${summary.solverMsMean} ms mean | |`,
  "",
  "| Scenario | Kind | Affected | Oracle max | Solver placed | Solver violations | Consent asked / min | Baseline placed | Baseline visits breaking a rule | ms |",
  "|---|---|---|---|---|---|---|---|---|---|",
  ...rows,
  "",
].join("\n");
writeFileSync(`${dir}/RESULTS.md`, md);
writeFileSync(`${dir}/results.json`, JSON.stringify(summary, null, 1));
console.log(summary);
